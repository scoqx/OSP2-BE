#!/bin/sh
# Copy the Quake Live movement from qalive into code/game/ql/.
#
# OSP2-BE predicts qalive (Quake Live) servers with the server's own
# bg_pmove.c / bg_slidemove.c. Keep them what the server runs: re-run this
# after every movement change in qalive, never edit the copies.
#
#   sh tools/sync_ql_pmove.sh [path to the qalive checkout]
#
# Needs a gcc (msys2 mingw or Linux) to list the symbols for ql_rename.h.
set -e
cd "$(dirname "$0")/.."
QL=${1:-../ioquakelive-main}
DST=code/game/ql

# Only the include of QL's q_shared.h changes: ql_shared.h builds the QL types
# on top of OSP2-BE's q_shared.h (QVM friendly) and renames the symbols.
# The .c files get a ql_ prefix: QVM asm files are named after the basename.
fix_include() {
    sed -e 's|#include "\.\./qcommon/q_shared\.h"|#include "ql_shared.h"|' "$1" > "$2"
}
fix_include "$QL/code/game/bg_pmove.c" "$DST/ql_bg_pmove.c"
fix_include "$QL/code/game/bg_slidemove.c" "$DST/ql_bg_slidemove.c"
for f in bg_pmove_jump.h bg_local.h bg_public.h; do
    fix_include "$QL/code/game/$f" "$DST/$f"
done
cp "$QL/code/qcommon/q3wire_tables.h" "$DST/q3wire_tables.h"
( cd "$QL" && git log -1 --format='qalive %h %cd' --date=short ) > "$DST/SOURCE"

# ql_rename.h: every symbol the QL files define (plus the bg_misc.c pieces
# ql_glue.c provides) gets a qlpm_ prefix, so they can live in the same QVM as
# OSP2-BE's own pmove.
TMP=$(mktemp -d)
: > "$DST/ql_rename.h"
for f in ql_bg_pmove ql_bg_slidemove; do
    gcc -DCGAME -w -c "$DST/$f.c" -o "$TMP/$f.o"
done
{
    echo "/* generated by tools/sync_ql_pmove.sh, do not edit */"
    echo "#ifndef QL_RENAME_H"
    echo "#define QL_RENAME_H"
    {
        # statics too: q3asm links every symbol as a global
        nm --defined-only "$TMP"/*.o | awk 'NF==3 && $2 ~ /^[TtDdBbRr]$/ && $3 !~ /\./ {print $3}'
        printf '%s\n' bg_itemlist bg_numItems bg_weaponReloadTime \
            BG_AddPredictableEventToPlayerstate BG_FindItemForHoldable \
            BG_HoldableForItemTag BG_PlayerHasPersistantPowerup
    } | sed 's/^_//' | sort -u | while read -r sym; do
        # q_shared.h inlines (VectorLength...) are OSP2-BE's own functions in a QVM
        grep -qE "^static ID_INLINE .*[^A-Za-z0-9_]$sym[[:space:]]*\(" code/qcommon/q_shared.h ||
            printf '#define %s qlpm_%s\n' "$sym" "$sym"
    done
    echo "#endif"
} > "$TMP/ql_rename.h"
mv "$TMP/ql_rename.h" "$DST/ql_rename.h"
rm -rf "$TMP"
echo "synced from $(cat $DST/SOURCE)"
